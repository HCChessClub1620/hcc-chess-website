// Run `node scripts/generate-gallery-pages.js` after changing gallery data.
const fs = require("node:fs");
const path = require("node:path");
const vm = require("node:vm");

const root = path.resolve(__dirname, "..");
const galleryDir = path.join(root, "pages", "gallery");
const marker = "<!-- Generated by scripts/generate-gallery-pages.js; do not edit directly. -->";
const startMarker = "  <!-- Gallery album pages -->";
const endMarker = "  <!-- End gallery album pages -->";
const origin = "https://hamiltonchessclub.org";
const check = process.argv.includes("--check");
const context = vm.createContext({ window: {} });

for (const file of ["gallery-learn.js", "gallery-tournaments.js", "gallery-hall-of-fame.js", "gallery-rising-champions.js"]) {
  vm.runInContext(fs.readFileSync(path.join(root, "js", file), "utf8"), context, { filename: file });
}

const gallery = context.window.hccGallery;
const albums = ["learn", "compete", "trail", "spotlight"].flatMap((category) => gallery[category].albums);
const slugs = new Set();
const escapeHtml = (value) => String(value).replace(/[&<>"']/g, (char) => ({
  "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;"
})[char]);
const albumUrl = (album) => `/pages/gallery/${album.id.toLowerCase()}/`;
const title = (album) => album.headings.length > 1
  ? `${album.headings[0]} | ${album.headings[album.headings.length - 1]}`
  : album.headings[0];
const photoAlt = (album, index) => {
  const names = [
    album.studentNames?.[index],
    album.secondStudentNames?.[index],
    album.centerStudentNames?.[index],
    ...(album.groupStudentNames?.[index] || [])
  ].filter(Boolean);
  return names.join(", ") || `${album.headings[0]} - photo ${index + 1}`;
};

for (const album of albums) {
  const slug = album.id.toLowerCase();
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || slugs.has(slug)) {
    throw new Error(`Invalid or duplicate album ID: ${album.id}`);
  }
  slugs.add(slug);
  if (!album.headings?.length || !album.images?.length ||
      album.images.some((image) => !image.startsWith("https://")) ||
      (album.cover && !album.cover.startsWith("https://"))) {
    throw new Error(`Album ${album.id} needs headings and absolute HTTPS images.`);
  }
}

const renderPage = (album, index) => {
  const url = origin + albumUrl(album);
  const pageTitle = `${title(album)} | Hamilton Chess Club`;
  const description = `Explore photos from ${album.headings.join(", ")} at Hamilton Chess Club.`;
  const preview = (album.cover || album.images[0]).replace("/f_auto,", "/f_jpg,");
  const previewAlt = `${album.headings[0]} - Hamilton Chess Club`;
  const subtitle = album.headings.slice(1).map((heading) => {
    const date = heading.match(/\b(?:\d{1,2}\s+)?(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*(?:\s*[-–]\s*(?:\d{1,2}\s+)?(?:jan|feb|mar|apr|may|jun|jul|aug|sep|oct|nov|dec)[a-z]*)?\s+\d{4}\b/i);
    if (!date) return `<span class="album-detail">${escapeHtml(heading)}</span>`;
    const before = heading.slice(0, date.index).trim();
    const after = heading.slice(date.index + date[0].length).trim();
    return [
      before && `<span class="album-detail">${escapeHtml(before)}</span>`,
      `<span class="album-date">${escapeHtml(date[0])}</span>`,
      after && `<span class="album-detail">${escapeHtml(after)}</span>`
    ].filter(Boolean).join(" ");
  }).join(" · ");
  const spotlight = album.id === "student-spotlight";
  const photos = album.images.map((image, imageIndex) => {
    const alt = photoAlt(album, imageIndex);
    const button = `<button class="album-photo" type="button" onclick="openTournament('${album.id}', ${imageIndex})" aria-label="View ${escapeHtml(alt)}"><img src="${escapeHtml(image)}" alt="${escapeHtml(alt)}" loading="lazy" /></button>`;
    if (!spotlight) return `        ${button}`;
    const student = gallery.spotlight.students[imageIndex];
    return `        <div class="spotlight-card">${button}<h4>${escapeHtml(student.name)}</h4><p>${escapeHtml(student.description)}</p></div>`;
  }).join("\n");
  const previous = index > 0
    ? `      <a href="${albumUrl(albums[index - 1])}">← Previous Album: ${escapeHtml(albums[index - 1].headings[0])}</a>`
    : "";
  const next = index < albums.length - 1
    ? `      <a href="${albumUrl(albums[index + 1])}">Next Album: ${escapeHtml(albums[index + 1].headings[0])} →</a>`
    : "";

  return `<!DOCTYPE html>
${marker}
<html lang="en">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(pageTitle)}</title>
  <meta name="description" content="${escapeHtml(description)}" />
  <link rel="canonical" href="${url}" />
  <meta property="og:title" content="${escapeHtml(pageTitle)}" />
  <meta property="og:description" content="${escapeHtml(description)}" />
  <meta property="og:image" content="${escapeHtml(preview)}" />
  <meta property="og:image:alt" content="${escapeHtml(previewAlt)}" />
  <meta property="og:url" content="${url}" />
  <meta property="og:type" content="website" />
  <meta name="twitter:card" content="summary_large_image" />
  <meta name="twitter:title" content="${escapeHtml(pageTitle)}" />
  <meta name="twitter:description" content="${escapeHtml(description)}" />
  <meta name="twitter:image" content="${escapeHtml(preview)}" />
  <meta name="twitter:image:alt" content="${escapeHtml(previewAlt)}" />
  <link rel="stylesheet" href="/css/style.css?v=20261122-album-details" />
  <link rel="preconnect" href="https://fonts.googleapis.com" />
  <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
  <link href="https://fonts.googleapis.com/css2?family=Poppins:wght@300;400;500;600;700&display=swap" rel="stylesheet" />
</head>
<body>
  <div id="site-header"></div>
  <section class="gallery-section">
    <div class="container">
      <div class="section-header album-header">
        <span class="section-tag">Memories &amp; Achievements</span>
        <h1>${escapeHtml(album.headings[0])}</h1>
${subtitle ? `        <p>${subtitle}</p>` : ""}
        <div class="tournament-actions" aria-label="Album actions">
          <button class="tournament-action like-button" type="button" data-tournament="${album.id}" onclick="toggleTournamentLike(event, this)" aria-label="Like this tournament" title="Like this tournament"><span class="like-icon" aria-hidden="true">&#9825;</span><span class="like-label">Like</span></button>
          <button class="tournament-action share-button" type="button" onclick="shareTournament(event, '${album.id}')" aria-label="Share this album" title="Share this album"><span class="share-icon" aria-hidden="true">&#8599;</span><span class="share-label">Share</span></button>
        </div>
      </div>
      <noscript><p>Enable JavaScript to view photos in the lightbox.</p></noscript>
      <div class="gallery-grid album-grid">
${photos}
      </div>
      <nav class="album-navigation" aria-label="Gallery navigation">
        <a href="/pages/gallery/">← Back to Gallery</a>
${previous}
${next}
      </nav>
    </div>
  </section>
  <div id="lightbox" class="lightbox album-lightbox" style="display:none;">
    <button class="lightbox-close" type="button" onclick="closeLightbox()" aria-label="Close lightbox">×</button>
    <button class="lightbox-prev" type="button" onclick="prevImage()" aria-label="Previous photo">❮</button>
    <div class="lightbox-media">
      <img id="lightbox-img" src="" alt="" />
      <div id="lightbox-image-counter" class="lightbox-image-counter" aria-live="polite"></div>
      <div id="lightbox-student-tag" class="lightbox-name-tag left" aria-live="polite"></div>
      <div id="lightbox-second-student-tag" class="lightbox-name-tag right" aria-live="polite"></div>
      <div id="lightbox-center-student-tag" class="lightbox-name-tag center" aria-live="polite"></div>
      <div id="lightbox-group-student-tags" class="lightbox-group-student-tags" aria-label="Students from left to right" hidden></div>
      <div id="lightbox-coach-tag" class="lightbox-coach-tag right"></div>
      <div id="lightbox-award-tag" class="lightbox-award-tag left" aria-live="polite"></div>
      <div id="lightbox-actions" class="lightbox-actions" aria-label="Album actions">
        <button id="lightbox-like-button" class="tournament-action like-button" type="button" onclick="toggleTournamentLike(event, this)" aria-label="Like this tournament" title="Like this tournament"><span class="like-icon" aria-hidden="true">&#9825;</span><span class="like-label">Like</span></button>
        <button id="lightbox-share-button" class="tournament-action share-button" type="button" onclick="shareTournament(event, this.dataset.tournament)" aria-label="Share this album" title="Share this album"><span class="share-icon" aria-hidden="true">&#8599;</span><span class="share-label">Share</span></button>
      </div>
    </div>
    <button class="lightbox-next" type="button" onclick="nextImage()" aria-label="Next photo">❯</button>
  </div>
  <div id="site-footer"></div>
  <script src="/js/gallery-learn.js?v=20261116-albums2"></script>
  <script src="/js/gallery-tournaments.js?v=20261116-albums3"></script>
  <script src="/js/gallery-hall-of-fame.js?v=20261122-winners"></script>
  <script src="/js/gallery-rising-champions.js?v=20261116-albums2"></script>
  <script src="/js/main.js?v=20261116-gallery-actions1"></script>
</body>
</html>
`;
};

const outputs = new Map(albums.map((album, index) => [
  path.join(galleryDir, album.id.toLowerCase(), "index.html"), renderPage(album, index)
]));
for (const entry of fs.readdirSync(galleryDir, { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const file = path.join(galleryDir, entry.name, "index.html");
  if (fs.existsSync(file) && fs.readFileSync(file, "utf8").includes(marker) && !outputs.has(file)) {
    throw new Error(`Obsolete generated album page must be reviewed: ${file}`);
  }
}

const sitemapPath = path.join(root, "sitemap.xml");
let sitemap = fs.readFileSync(sitemapPath, "utf8").replace(/\r\n/g, "\n");
const albumEntries = [startMarker, ...albums.map((album) =>
  `  <url><loc>${origin}${albumUrl(album)}</loc></url>`
), endMarker].join("\n");
if (sitemap.includes(startMarker) && sitemap.includes(endMarker)) {
  sitemap = sitemap.slice(0, sitemap.indexOf(startMarker)) + albumEntries +
    sitemap.slice(sitemap.indexOf(endMarker) + endMarker.length);
} else if (!sitemap.includes(startMarker) && !sitemap.includes(endMarker)) {
  const galleryEntry = `  <url><loc>${origin}/pages/gallery/</loc></url>`;
  if (!sitemap.includes(galleryEntry)) throw new Error("Gallery entry missing from sitemap.");
  sitemap = sitemap.replace(galleryEntry, `${galleryEntry}\n${albumEntries}`);
} else {
  throw new Error("Incomplete generated album markers in sitemap.");
}
outputs.set(sitemapPath, sitemap);

let outOfDate = false;
for (const [file, content] of outputs) {
  const existing = fs.existsSync(file) ? fs.readFileSync(file, "utf8").replace(/\r\n/g, "\n") : null;
  if (existing === content) continue;
  if (file !== sitemapPath && existing !== null && !existing.includes(marker)) {
    throw new Error(`Refusing to overwrite a non-generated page: ${file}`);
  }
  if (check) {
    console.error(`Out of date: ${path.relative(root, file)}`);
    outOfDate = true;
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content, "utf8");
    console.log(`Updated ${path.relative(root, file)}`);
  }
}
if (outOfDate) process.exitCode = 1;
else console.log(`${albums.length} album pages ${check ? "verified" : "generated"}.`);
